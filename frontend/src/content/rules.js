/* ───────────── 섯다 족보 확률 (20장에서 2장·3장) ───────────── */

const SEOTDA_GROUPS = [
  ['38광땡', (h) => h.code === 'gwang38'],
  ['18광땡·13광땡', (h) => h.code === 'gwang13' || h.code === 'gwang18'],
  ['장땡(10땡)', (h) => h.code === 'ttaeng' && h.month === 10],
  ['9땡 ~ 2땡', (h) => h.code === 'ttaeng' && h.month > 1 && h.month < 10],
  ['삥땡(1땡)', (h) => h.code === 'ttaeng' && h.month === 1],
  ['알리 (1+2)', (h) => h.code === 'ali'],
  ['독사 (1+4)', (h) => h.code === 'doksa'],
  ['구삥 (1+9)', (h) => h.code === 'gubbing'],
  ['장삥 (1+10)', (h) => h.code === 'jangbbing'],
  ['장사 (4+10)', (h) => h.code === 'jangsa'],
  ['세륙 (4+6)', (h) => h.code === 'seryuk'],
  ['갑오 (9끗)', (h) => h.code === 'kkut' && h.kkut === 9],
  ['5끗 ~ 8끗', (h) => h.code === 'kkut' && h.kkut >= 5 && h.kkut <= 8],
  ['1끗 ~ 4끗', (h) => h.code === 'kkut' && h.kkut >= 1 && h.kkut <= 4],
  ['망통 (0끗)', (h) => h.code === 'kkut' && h.kkut === 0],
];

const groupOf = (h) => SEOTDA_GROUPS.findIndex(([, f]) => f(h));

const seotdaOdds = () => {
  const two = SEOTDA_GROUPS.map(() => 0);
  const three = SEOTDA_GROUPS.map(() => 0);
  let n2 = 0;
  let n3 = 0;
  for (let a = 0; a < 20; a++) {
    for (let b = a + 1; b < 20; b++) {
      two[groupOf(classify(a, b))]++;
      n2++;
      for (let c = b + 1; c < 20; c++) {
        // 3장 섯다: 세 조합 중 가장 센 2장 (특수패는 끗으로 본 기본 세기)
        const best = [classify(a, b), classify(a, c), classify(b, c)].sort((x, y) => y.base - x.base)[0];
        three[groupOf(best)]++;
        n3++;
      }
    }
  }
  const pct = (k, n) => `${((k / n) * 100).toFixed(2)}%`;
  return SEOTDA_GROUPS.map(([name], i) => [name, `${two[i]} / ${n2}`, pct(two[i], n2), pct(three[i], n3)]);
};

